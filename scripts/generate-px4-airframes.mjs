import { mkdir, readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'

const QGC_COMMIT = 'f4d5cb0bc975294b51d050fc8878e5600e93b907'
const SOURCE = `https://raw.githubusercontent.com/mavlink/qgroundcontrol/${QGC_COMMIT}/src/AutoPilotPlugins/PX4/AirframeFactMetaData.xml`
const OUTPUT = path.resolve('src/shared/generated/px4Airframes.ts')

function argumentValue(name) {
  const index = process.argv.indexOf(name)
  return index >= 0 ? process.argv[index + 1] : null
}

function decodeXml(value) {
  return value
    .replaceAll('&quot;', '"')
    .replaceAll('&apos;', "'")
    .replaceAll('&lt;', '<')
    .replaceAll('&gt;', '>')
    .replaceAll('&amp;', '&')
}

async function loadSource() {
  const local = argumentValue('--source')
  if (local) return readFile(path.resolve(local), 'utf8')
  const response = await fetch(SOURCE)
  if (!response.ok) throw new Error(`Failed to download ${SOURCE}: HTTP ${response.status}`)
  return response.text()
}

function parseAirframes(xml) {
  const airframes = []
  const groupPattern = /<airframe_group\s+name="([^"]+)"[^>]*>([\s\S]*?)<\/airframe_group>/g
  for (const groupMatch of xml.matchAll(groupPattern)) {
    const group = decodeXml(groupMatch[1])
    const framePattern = /<airframe\s+name="([^"]+)"\s+id="(\d+)"[^>]*>([\s\S]*?)<\/airframe>/g
    for (const frameMatch of groupMatch[2].matchAll(framePattern)) {
      const outputs = [...frameMatch[3].matchAll(/<output\s+name="([^"]+)">([^<]*)<\/output>/g)]
        .map((match) => `${decodeXml(match[1])}: ${decodeXml(match[2].trim())}`)
      airframes.push({
        autostartId: Number(frameMatch[2]),
        name: decodeXml(frameMatch[1]),
        group,
        outputs,
      })
    }
  }
  return airframes.sort((left, right) => left.group.localeCompare(right.group) || left.name.localeCompare(right.name))
}

const airframes = parseAirframes(await loadSource())
if (airframes.length < 20) throw new Error(`Unexpected QGC airframe catalog size: ${airframes.length}`)
await mkdir(path.dirname(OUTPUT), { recursive: true })
await writeFile(OUTPUT, `// Generated by scripts/generate-px4-airframes.mjs from QGC ${QGC_COMMIT}.\n`
  + `// QGroundControl is used under its Apache-2.0 license option. Do not edit by hand.\n`
  + `export interface Px4AirframeCatalogEntry {\n  autostartId: number\n  name: string\n  group: string\n  outputs: string[]\n}\n\n`
  + `export const PX4_AIRFRAME_SOURCE = ${JSON.stringify(SOURCE)}\n`
  + `export const PX4_AIRFRAMES: readonly Px4AirframeCatalogEntry[] = ${JSON.stringify(airframes, null, 2)}\n`, 'utf8')
console.log(`PX4: generated ${airframes.length} airframes from QGC ${QGC_COMMIT}`)
